# โจทย์ข้อที่ 2: ตรวจสอบเลขคู่ หรือ เลขคี่
# Input: จำนวนเต็ม n
# Output: พิมพ์ "Even" ถ้าเป็นเลขคู่ หรือ "Odd" ถ้าเป็นเลขคี่
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
n = int(input("กรุณาใส่เลข: "))

if n == 2^4^6^8^10:
    print("Even")
elif n == 1^3^5^7^9:
    print("Odd")
